#!/usr/bin/env python3
"""Generate the IL2CPP forwarder for one Unity version.

Input: a list of symbols (Mach-O names, leading underscore) that the iOS engine
(libiPhone-lib.a) expects the static IL2CPP library to define. diagnostics.sh
writes it as engine-needs-from-ga.txt.

Output:
  mp27_stubs.s   one arm64 trampoline per function: load target from
                 mp27_table[i] and branch. Arguments, return values and the
                 stack are untouched, so no IL2CPP type headers are needed.
  mp27_table.c   the pointer table plus the dlsym names.

Symbols named with --override get a table slot but no stub: mp27_loader.m
implements them in C and calls the real function through mp27_real().

Usage: gen_forwarder.py SYMBOLS.txt OUTDIR [--override il2cpp_init ...]
"""
import argparse
import os
import re
import sys

DEFAULT_OVERRIDES = ["il2cpp_init", "il2cpp_init_utf16", "il2cpp_set_data_dir",
                     "il2cpp_class_get_methods"]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("symbols")
    ap.add_argument("outdir")
    ap.add_argument("--override", nargs="*", default=DEFAULT_OVERRIDES)
    a = ap.parse_args(argv)

    names = []
    with open(a.symbols) as fh:
        for line in fh:
            s = line.strip()
            if not s or s.startswith("#"):
                continue
            if not re.match(r"^_[A-Za-z_][A-Za-z0-9_$]*$", s):
                print(f"skipping non-C symbol {s}", file=sys.stderr)
                continue
            names.append(s[1:])
    names = sorted(set(names))
    overrides = set(a.override)
    if len(names) > 4000:
        raise SystemExit("too many symbols for a scaled 12-bit ldr offset")

    os.makedirs(a.outdir, exist_ok=True)
    with open(os.path.join(a.outdir, "mp27_table.c"), "w") as fh:
        fh.write("// Generated by phase0/forwarder/gen_forwarder.py. Do not edit.\n")
        fh.write(f"const unsigned mp27_count = {len(names)};\n")
        fh.write(f"void *mp27_table[{len(names)}];\n")
        fh.write("const char *const mp27_names[] = {\n")
        for n in names:
            fh.write(f'    "{n}",\n')
        fh.write("};\n")

    with open(os.path.join(a.outdir, "mp27_stubs.s"), "w") as fh:
        fh.write("// Generated by phase0/forwarder/gen_forwarder.py. Do not edit.\n")
        fh.write(".section __TEXT,__text,regular,pure_instructions\n")
        for i, n in enumerate(names):
            if n in overrides:
                continue
            fh.write(f".globl _{n}\n.p2align 2\n_{n}:\n")
            fh.write("    adrp x16, _mp27_table@PAGE\n")
            fh.write("    add  x16, x16, _mp27_table@PAGEOFF\n")
            fh.write(f"    ldr  x16, [x16, #{8 * i}]\n")
            fh.write("    br   x16\n")
    print(f"{len(names)} symbols, {len(names) - len(overrides & set(names))} stubs, "
          f"{len(overrides & set(names))} overrides -> {a.outdir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
